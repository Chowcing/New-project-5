CREATE TABLE transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  type VARCHAR(16) NOT NULL,
  item_name VARCHAR(64),
  amount DECIMAL(12,2) NOT NULL,
  occurred_at TIMESTAMP NOT NULL,
  channel VARCHAR(16) NOT NULL,
  online_app VARCHAR(64),
  online_platform_id BIGINT,
  offline_place VARCHAR(128),
  payment_method_id BIGINT NOT NULL,
  payment_method_name VARCHAR(64) NOT NULL,
  category_id BIGINT NOT NULL,
  note VARCHAR(255),
  trashed_at TIMESTAMP,
  deleted TINYINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE budgets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  month VARCHAR(7) NOT NULL,
  category_id BIGINT,
  amount DECIMAL(12,2) NOT NULL,
  deleted TINYINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE recurring_rules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  name VARCHAR(64) NOT NULL,
  type VARCHAR(16) NOT NULL,
  item_name VARCHAR(64),
  amount DECIMAL(12,2) NOT NULL,
  channel VARCHAR(16) NOT NULL,
  online_app VARCHAR(64),
  offline_place VARCHAR(128),
  payment_method_id BIGINT NOT NULL,
  payment_method_name VARCHAR(64) NOT NULL,
  category_id BIGINT NOT NULL,
  category_name VARCHAR(64) NOT NULL,
  note VARCHAR(255),
  schedule_type VARCHAR(16) NOT NULL,
  interval_value INT NOT NULL,
  day_of_month INT,
  weekday VARCHAR(16),
  start_date DATE NOT NULL,
  next_run_date DATE,
  end_date DATE,
  reminder_days_before INT NOT NULL DEFAULT 0,
  status VARCHAR(16) NOT NULL,
  deleted TINYINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE recurring_rule_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  rule_id BIGINT NOT NULL,
  rule_name VARCHAR(64) NOT NULL,
  due_date DATE NOT NULL,
  reminder_days_before INT NOT NULL DEFAULT 0,
  type VARCHAR(16) NOT NULL,
  item_name VARCHAR(64),
  amount DECIMAL(12,2) NOT NULL,
  channel VARCHAR(16) NOT NULL,
  online_app VARCHAR(64),
  offline_place VARCHAR(128),
  payment_method_id BIGINT NOT NULL,
  category_id BIGINT NOT NULL,
  note VARCHAR(255),
  status VARCHAR(16) NOT NULL,
  transaction_id BIGINT,
  error_message VARCHAR(255),
  processed_at TIMESTAMP,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (rule_id, due_date)
);
